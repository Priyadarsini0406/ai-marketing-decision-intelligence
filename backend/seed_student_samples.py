"""Create two clearly marked illustrative lead records for student accounts.

The website-activity values are synthetic examples. Scores, SHAP explanations,
and segment labels are generated by the saved project artifacts; they must not
be treated as real admission decisions.

Usage from the repository root:
    npm run python -- backend/seed_student_samples.py --email-one first@example.com --email-two second@example.com
"""
from __future__ import annotations

import argparse
import json
from datetime import date

import ml_service as svc
from database.connection import Base, SessionLocal, engine
from database.models import Lead, MLPrediction, StudentEnquiry, User


SAMPLE_ACTIVITY = (
    {"website_visits": 10, "pages_per_visit": 3.2, "time_on_site": 420.0},
    {"website_visits": 5, "pages_per_visit": 1.8, "time_on_site": 160.0},
)


def seed(email_one: str, email_two: str) -> list[dict]:
    Base.metadata.create_all(bind=engine)
    pipeline, contract = svc.load_pipeline()
    segment_artifact = svc.load_segments()
    results = []

    with SessionLocal.begin() as db:
        for email, activity in zip((email_one.lower(), email_two.lower()), SAMPLE_ACTIVITY):
            account = db.query(User).filter(User.email == email, User.role == "student").one_or_none()
            if account is None:
                raise ValueError(f"Student account not found: {email}")

            profile = account.profile or {}
            enquiry = (db.query(StudentEnquiry)
                       .filter(StudentEnquiry.student_user_id == account.id)
                       .order_by(StudentEnquiry.created_at.desc()).first())
            customer_id = f"SAMPLE-ACCOUNT-{account.id[:8]}"
            lead = db.query(Lead).filter(Lead.student_id == account.id).one_or_none()
            if lead is not None and lead.customer_id != customer_id:
                raise ValueError(f"{account.name} already has a non-sample lead; leaving it unchanged")
            if lead is None:
                lead = Lead(student_id=account.id)
                db.add(lead)

            lead.student_name = account.name
            lead.course_interested = ((enquiry.course_interested if enquiry else None)
                                      or profile.get("course_interested"))
            lead.qualification = ((enquiry.qualification if enquiry else None)
                                  or profile.get("qualification"))
            lead.academic_score = enquiry.academic_score if enquiry else None
            lead.location = ((enquiry.location if enquiry else None) or profile.get("city"))
            lead.admission_year = date.today().year
            lead.enquiry_date = date.today().isoformat()
            lead.lead_status = enquiry.status if enquiry else "Registered"
            lead.enquiry_source = "Sample data (synthetic website activity)"
            lead.customer_id = customer_id
            lead.website_visits = activity["website_visits"]
            lead.pages_per_visit = activity["pages_per_visit"]
            lead.time_on_site = activity["time_on_site"]
            lead.conversion = None
            db.flush()

            frame, _ = svc.frame_for_lead(lead, contract)
            probability = float(pipeline.predict_proba(frame)[0, 1])
            clusters, names = svc.assign_segments(segment_artifact, pipeline, frame)
            # Keep the cluster name, but omit its historical dominant-source
            # suffix because that source was not observed for this sample.
            segment_name = segment_artifact.get("names", {}).get(int(clusters[0]), names[0])
            explanation = svc.explain_frame(
                pipeline, frame, contract["numeric_features"], contract["categorical_features"], top_n=5
            )[0]
            explanation["sample_data"] = True
            explanation["note"] = (
                "Synthetic website activity values were used; other model features were imputed. "
                "This is not a real admission decision."
            )

            prediction = db.query(MLPrediction).filter(MLPrediction.lead_id == lead.id).one_or_none()
            if prediction is None:
                prediction = MLPrediction(lead_id=lead.id)
                db.add(prediction)
            prediction.conversion_probability = probability
            prediction.admission_probability = probability
            prediction.lead_score = svc.score_band(probability)
            prediction.segment_cluster = clusters[0]
            prediction.segment_name = segment_name
            prediction.shap_explanation = explanation
            results.append({"student": account.name, "probability": probability,
                            "score": prediction.lead_score, "segment": segment_name})

    return results


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--email-one", required=True, help="First student account email")
    parser.add_argument("--email-two", required=True, help="Second student account email")
    args = parser.parse_args()
    print(json.dumps(seed(args.email_one, args.email_two), indent=2))


if __name__ == "__main__":
    main()
